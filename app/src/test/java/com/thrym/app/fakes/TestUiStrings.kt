package com.thrym.app.fakes

import com.thrym.app.presentation.common.UiStrings
import java.io.File
import java.util.Locale
import java.util.Properties
import javax.xml.parsers.DocumentBuilderFactory
import org.w3c.dom.Element

/**
 * Reads the real app copy for JVM tests, without an Android Context or duplicated text.
 *
 * The object itself is the default (English) copy from `values/`, formatted with [Locale.US],
 * as on an en-US device. [german] overlays `values-de/` on `values/` and formats with
 * [Locale.GERMANY]. Pin a language only where the wording itself is under test; otherwise
 * resolve the expected text through the same instance the code under test uses.
 */
object TestUiStrings : UiStrings by ResourceTestUiStrings(qualifier = null, locale = Locale.US) {
    /** German copy (`values-de/` over `values/`), formatted with [Locale.GERMANY]. */
    val german: UiStrings by lazy { ResourceTestUiStrings(qualifier = "de", locale = Locale.GERMANY) }
}

/** [UiStrings] backed by the module resource XML files; [qualifier] is e.g. "de" for `values-de/`. */
class ResourceTestUiStrings(private val qualifier: String?, override val locale: Locale) : UiStrings {
    private class Table(val strings: Map<Int, String>, val plurals: Map<Int, Map<String, String>>)

    private val table: Table by lazy { load() }

    override fun get(resourceId: Int, vararg args: Any): String {
        val template = checkNotNull(table.strings[resourceId]) { "Missing string resource $resourceId" }
        return if (args.isEmpty()) template else String.format(locale, template, *args)
    }

    /** English and German share the one/other rule: "one" only for exactly 1. */
    override fun getQuantity(resourceId: Int, quantity: Int, vararg args: Any): String {
        val forms = checkNotNull(table.plurals[resourceId]) { "Missing plurals resource $resourceId" }
        val template = checkNotNull(forms[if (quantity == 1) "one" else "other"] ?: forms["other"]) {
            "Plurals resource $resourceId has no 'other' form"
        }
        return if (args.isEmpty()) template else String.format(locale, template, *args)
    }

    private fun load(): Table {
        val root = generateSequence(File(".").absoluteFile) { it.parentFile }
            .first { File(it, "settings.gradle.kts").isFile }
        val modules = listOf("core/designsystem") + File(root, "feature").listFiles()
            .orEmpty().filter { it.isDirectory }.map { "feature/${it.name}" }.sorted()
        val strings = mutableMapOf<Int, String>()
        val plurals = mutableMapOf<Int, Map<String, String>>()
        val builder = DocumentBuilderFactory.newInstance().newDocumentBuilder()
        for (module in modules) {
            val packageName = "com.thrym.${module.replace('/', '.')}"
            val stringClass = Class.forName("$packageName.R\$string")
            val pluralsClass = runCatching { Class.forName("$packageName.R\$plurals") }.getOrNull()
            // The default folder first, then the qualified one on top, like Android's fallback.
            val directories = listOfNotNull("values", qualifier?.let { "values-$it" })
            for (directory in directories) {
                val files = File(root, "$module/src/main/res/$directory").listFiles().orEmpty()
                for (file in files.filter { it.extension == "xml" }.sortedBy { it.name }) {
                    val document = builder.parse(file)
                    val nodes = document.getElementsByTagName("string")
                    for (index in 0 until nodes.length) {
                        val node = nodes.item(index) as Element
                        val id = stringClass.getField(node.getAttribute("name")).getInt(null)
                        strings[id] = unescapeAndroidString(node.textContent)
                    }
                    val pluralNodes = document.getElementsByTagName("plurals")
                    for (index in 0 until pluralNodes.length) {
                        val node = pluralNodes.item(index) as Element
                        val id = checkNotNull(pluralsClass).getField(node.getAttribute("name")).getInt(null)
                        val items = node.getElementsByTagName("item")
                        plurals[id] = (0 until items.length).associate { itemIndex ->
                            val item = items.item(itemIndex) as Element
                            item.getAttribute("quantity") to unescapeAndroidString(item.textContent)
                        }
                    }
                }
            }
        }
        // app_name is generated by Gradle (resValue from branding.properties), not an XML file.
        runCatching { Class.forName("com.thrym.core.designsystem.R\$string").getField("app_name").getInt(null) }
            .getOrNull()
            ?.let { id -> strings.getOrPut(id) { appDisplayName(root) } }
        return Table(strings, plurals)
    }

    private fun appDisplayName(root: File): String = Properties().run {
        File(root, "branding.properties").reader(Charsets.UTF_8).use { load(it) }
        getProperty("appDisplayName").trim()
    }
}

/**
 * Resolves a resource string the way aapt2 compiles it: XML entities are already decoded by the
 * parser; unquoted whitespace runs collapse to one space and are trimmed at both ends; text in
 * double quotes keeps its whitespace and loses the quotes; `\n`, `\t`, `\uXXXX` and escaped
 * characters such as `\'`, `\"`, `\@`, `\?` and `\\` become the literal character.
 */
internal fun unescapeAndroidString(raw: String): String {
    // Collapsible (unquoted) whitespace is marked first, so it can be trimmed at the ends only.
    val collapsibleSpace = '\u0000'
    val out = StringBuilder()
    var quoted = false
    var index = 0
    while (index < raw.length) {
        val char = raw[index]
        when {
            char == '\\' && index + 1 < raw.length -> {
                val next = raw[index + 1]
                index += 2
                when (next) {
                    'n' -> out.append('\n')
                    't' -> out.append('\t')
                    'u' -> {
                        val hex = raw.substring(index, minOf(index + 4, raw.length))
                        val codePoint = hex.takeIf { it.length == 4 }?.toIntOrNull(16)
                        if (codePoint != null) {
                            out.append(codePoint.toChar())
                            index += 4
                        } else {
                            out.append('u')
                        }
                    }
                    else -> out.append(next)
                }
                continue
            }
            char == '"' -> quoted = !quoted
            !quoted && char.isWhitespace() -> {
                if (out.lastOrNull() != collapsibleSpace) out.append(collapsibleSpace)
            }
            else -> out.append(char)
        }
        index++
    }
    return out.toString().trim(collapsibleSpace).replace(collapsibleSpace, ' ')
}
