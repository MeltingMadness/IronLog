// Barbell Plate Color Coding (Olympic & Gym standard)
object PlateColors {
    val Plate25 = Color(0xFFEF4444)  // Rot (25 kg)
    val Plate20 = Color(0xFF3B82F6)  // Blau (20 kg)
    val Plate15 = Color(0xFFEAB308)  // Gelb (15 kg)
    val Plate10 = Color(0xFF10B981)  // Grün (10 kg)
    val Plate5 = Color(0xFFF1F5F9)   // Weiß / Hellgrau (5 kg)
    val Plate2_5 = Color(0xFF475569) // Schwarz / Anthrazit (2.5 kg)
    val Plate1_25 = Color(0xFF94A3B8)// Silber / Chrom (1.25 kg)
    val Plate0_5 = Color(0xFFCBD5E1) // Silber / Slate (0.5 kg)

    fun forWeight(weightKg: Double): Color = when {
        weightKg >= 24.9 -> Plate25
        weightKg >= 19.9 -> Plate20
        weightKg >= 14.9 -> Plate15
        weightKg >= 9.9  -> Plate10
        weightKg >= 4.9  -> Plate5
        weightKg >= 2.4  -> Plate2_5
        weightKg >= 1.2  -> Plate1_25
        else             -> Plate0_5
    }

    fun onPlateColor(weightKg: Double): Color = when {
        weightKg >= 4.9 && weightKg < 9.9 -> Color(0xFF0F172A) // Dark text on 5kg white plate
        weightKg < 1.0 -> Color(0xFF0F172A)                   // Dark text on 0.5kg slate plate
        else -> Color(0xFFFFFFFF)                              // White text on colored plates
    }
}
